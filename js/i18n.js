  function lookup(dict, key) {
    var parts = key.split(".");
    var cur = dict;
    for (var i = 0; i < parts.length; i++) {
      if (!cur || typeof cur !== "object") return null;
      cur = cur[parts[i]];
    }
    return typeof cur === "string" ? cur : null;
  }

  function t(lang, key) {
    var primary = STRINGS[lang] || STRINGS.en;
    return lookup(primary, key) || lookup(STRINGS.en, key) || "";
  }

  function apply(lang) {
    if (lang !== "he" && lang !== "en") lang = "en";
    var title = t(lang, "meta.title");
    var page = document.body && document.body.getAttribute("data-page");
    if (page === "privacy") title = t(lang, "legal.privacyTitle");
    if (page === "terms") title = t(lang, "legal.termsTitle");
    if (page === "404") title = t(lang, "legal.notFoundTitle");
    if (title) document.title = title;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var val = t(lang, el.getAttribute("data-i18n"));
      if (val) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var val = t(lang, el.getAttribute("data-i18n-placeholder"));
      if (val) el.setAttribute("placeholder", val);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var val = t(lang, el.getAttribute("data-i18n-aria"));
      if (val) el.setAttribute("aria-label", val);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var val = t(lang, el.getAttribute("data-i18n-title"));
      if (val) el.setAttribute("title", val);
    });

    document.querySelectorAll(".legal-lang-note").forEach(function (el) {
      el.hidden = lang !== "he";
    });
  }

